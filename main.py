import os

TEXT = "Friend, picture a post road joining every house and library on earth, so swift that a letter sent at breakfast can be answered from across the sea before your cup is cold."


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(TEXT)


if __name__ == "__main__":
    main()
